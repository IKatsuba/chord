/// Writes `lib/sources.g.dart`: the code chord_tui's pages show, copied from
/// the files themselves so it cannot drift from them. The build runs it
/// before compiling; a site test fails when the written file is stale.
///
///     dart run tool/sources.dart
library;

import 'dart:io';

import 'package:path/path.dart' as p;

/// The examples whose files the pages show: README's, then the gallery's.
const sourceExamples = [
  'main',
  'demo',
  'markdown',
  'picker',
  'form',
  'text_area',
  'diff',
  'dialog',
  'layers',
  'mouse',
];

/// The heading README's testing example sits under.
const testingHeading = '## Testing';

/// The first Dart block under [testingHeading] in [readme].
String testingExample(String readme) {
  final start = readme.indexOf('\n$testingHeading\n');
  if (start < 0) throw StateError('README has no "$testingHeading"');
  final open = readme.indexOf('```dart\n', start);
  if (open < 0) throw StateError('"$testingHeading" has no Dart block');
  final body = open + '```dart\n'.length;
  final close = readme.indexOf('\n```', body);
  if (close < 0) throw StateError('"$testingHeading" block is not closed');
  return readme.substring(body, close + 1);
}

/// [text] as adjacent Dart string literals, a line each, at [indent].
String _literal(String text, String indent) {
  final lines = text.split('\n');
  if (lines.last.isEmpty) lines.removeLast();
  String escape(String line) => line
      .replaceAll(r'\', r'\\')
      .replaceAll(r'$', r'\$')
      .replaceAll("'", r"\'");
  return [for (final line in lines) "$indent'${escape(line)}\\n'"].join('\n');
}

/// The contents of `lib/sources.g.dart` for the repository at [root].
String generateSources(String root) {
  final framework = p.join(root, 'packages', 'chord_tui');
  final out = StringBuffer()
    ..writeln('// Generated by tool/sources.dart from the files it names;')
    ..writeln(
      '// do not edit. Run `dart run tool/sources.dart` after a change.',
    )
    ..writeln()
    ..writeln(
      "/// Each example's file, by name, as `example/<name>.dart` has it.",
    )
    ..writeln('const exampleSources = <String, String>{');
  for (final name in sourceExamples) {
    final text = File(
      p.join(framework, 'example', '$name.dart'),
    ).readAsStringSync();
    out
      ..writeln("  '$name':")
      ..write(_literal(text, '      '))
      ..writeln(',');
  }
  out
    ..writeln('};')
    ..writeln()
    ..writeln("/// README's testing example, as its Testing section has it.")
    ..writeln('const testingSource =')
    ..write(
      _literal(
        testingExample(File(p.join(framework, 'README.md')).readAsStringSync()),
        '    ',
      ),
    )
    ..writeln(';');
  return out.toString();
}

/// Where the generated file goes, under the site at [siteDir].
String sourcesPath(String siteDir) => p.join(siteDir, 'lib', 'sources.g.dart');

/// Writes the generated file for the site at [siteDir].
void writeSources(String siteDir) {
  final file = File(sourcesPath(siteDir));
  final text = generateSources(p.dirname(siteDir));
  // Unchanged, it is left alone: a build beside this one may be compiling
  // it, and a rewrite truncates it first.
  if (file.existsSync() && file.readAsStringSync() == text) return;
  file.writeAsStringSync(text);
}

void main() {
  final siteDir = p.dirname(
    p.dirname(p.absolute(Platform.script.toFilePath())),
  );
  writeSources(siteDir);
  stdout.writeln('wrote ${p.relative(sourcesPath(siteDir))}');
}
