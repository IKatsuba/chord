    r\'\'\'$json\'\'\';
''');
    stdout.writeln('Wrote ${p.relative(file.path)}: ${json.length} bytes.');
    return 0;
  } finally {
    scratch.deleteSync(recursive: true);
  }
}

Map<String, Object?> _provider(Map<String, Object?> provider) => {
  'id': provider['id'],
  'model_match': ?provider['model_match'],
  'fallback_model_providers': ?provider['fallback_model_providers'],
  'models': [
    for (final model in provider['models'] as List)
      if (model case final Map<String, Object?> model)
        {
          'id': model['id'],
          'match': model['match'],
          'prices': model['prices'],
          'context_window': ?model['context_window'],
        },
  ],
};
