/**
 * Rasterise Chorded's mark into src/ui/header/mark.ts.
 *
 *   bun run dev mark   render scripts/mark.svg and rewrite the module
 *
 * The mark is drawn in half blocks, so each grid is the SVG sampled per half
 * cell, as docs/design/CHD-201.md lays out. chord never reads the SVG at run
 * time, so the shape moves only when this runs and the diff is committed.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { initWasm, Resvg } from '@resvg/resvg-wasm';
import { formatModule } from '../format.ts';

/** The rows of cells the header's mark is tall. */
export const ROWS = 4;

/** The rows of cells the startup splash's mark is tall (CHD-241). */
export const SPLASH_ROWS = 8;

/**
 * A half cell is filled at this share of its area. At 4 rows every half cell
 * is below 0.29 or above 0.88, and at 8 below 0.29 or at 0.59 and above, so
 * antialiasing cannot move either grid.
 */
export const THRESHOLD = 0.5;

// Pixels along each side of a half cell, so a cell's edges fall on pixel
// edges and its coverage is a plain mean of alpha.
const SAMPLES = 32;

/** The size of an SVG's viewBox, in its own units. */
export interface ViewBox {
  readonly width: number;
  readonly height: number;
}

/**
 * The SVG's viewBox. resvg's own `width` rounds the mark's 54.367 to 54,
 * which would tilt the gradient, so the attribute is read as written.
 */
export function viewBox(svg: string): ViewBox {
  const [, , width = 0, height = 0] =
    /viewBox="([^"]+)"/
      .exec(svg)?.[1]
      ?.trim()
      .split(/[\s,]+/)
      .map(Number) ?? [];

  if (!(width > 0 && height > 0)) {
    throw new Error('The SVG has no viewBox with a width and a height.');
  }

  return { width, height };
}

/** The mark `rows` tall: each half cell's coverage, `[halfRow][column]`. */
export function coverage(svg: string, rows: number): number[][] {
  const box = viewBox(svg);
  // Half cells are taken as square, the mark's height spanning 2 × rows.
  const unit = box.height / (2 * rows);
  const resvg = new Resvg(svg, {
    fitTo: { mode: 'zoom', value: SAMPLES / unit },
  });
  const columns = Math.ceil(box.width / unit);
  const { width, height, pixels } = resvg.render();

  return Array.from({ length: 2 * rows }, (_, row) =>
    Array.from({ length: columns }, (_, column) => {
      let alpha = 0;

      for (let y = row * SAMPLES; y < (row + 1) * SAMPLES; y++) {
        for (let x = column * SAMPLES; x < (column + 1) * SAMPLES; x++) {
          // The render stops at the SVG's own width, short of the last column.
          if (x < width && y < height) {
            alpha += pixels[(y * width + x) * 4 + 3] ?? 0;
          }
        }
      }

      return alpha / 255 / SAMPLES / SAMPLES;
    }),
  );
}

/**
 * The half cells filled at the threshold, each as its place on the gradient
 * from the viewBox's top-left to its bottom-right, measured at its centre;
 * `null` where empty. Columns empty at the right are trimmed.
 */
export function markGrid(
  covered: readonly (readonly number[])[],
  rows: number,
  box: ViewBox,
): (number | null)[][] {
  const unit = box.height / (2 * rows);
  const span = box.width ** 2 + box.height ** 2;
  const grid = covered.map((line, row) =>
    line.map((share, column) => {
      if (share < THRESHOLD) {
        return null;
      }

      const x = (column + 0.5) * unit;
      const y = (row + 0.5) * unit;
      const t = Math.min(
        1,
        Math.max(0, (x * box.width + y * box.height) / span),
      );

      // Four places are finer than any terminal can show, and keep the
      // module the same from one run to the next.
      return Math.round(t * 10_000) / 10_000;
    }),
  );

  const columns = Math.max(
    0,
    ...grid.map((line) => line.findLastIndex((t) => t !== null) + 1),
  );

  return grid.map((line) => line.slice(0, columns));
}

/** The source of src/ui/header/mark.ts, before the formatter lays it out. */
export function markModule(
  grid: (number | null)[][],
  splash: (number | null)[][],
): string {
  return `// Generated by \`bun run dev mark\` from scripts/mark.svg, Chorded's mark.
// Do not edit: run the task again and commit the diff.

/**
 * The mark in half cells, \`[halfRow][column]\`: a filled half cell's place
 * on the mark's diagonal gradient, 0 at the top-left and 1 at the
 * bottom-right, or \`null\` where the half cell is empty. Two half rows make
 * one row of cells.
 */
export type MarkGrid = readonly (readonly (number | null)[])[];

/** The mark, ${ROWS} rows tall. */
export const MARK: MarkGrid = ${JSON.stringify(grid)};

/** The startup splash's mark, ${SPLASH_ROWS} rows tall. */
export const SPLASH_MARK: MarkGrid = ${JSON.stringify(splash)};
`;
}

/** Rasterises scripts/mark.svg and rewrites src/ui/header/mark.ts. */
export async function mark(): Promise<void> {
  const wasm = new URL(import.meta.resolve('@resvg/resvg-wasm/index_bg.wasm'));

  await initWasm(await readFile(wasm));

  const svg = await readFile(new URL('../mark.svg', import.meta.url), 'utf8');
  const size = viewBox(svg);
  const grid = markGrid(coverage(svg, ROWS), ROWS, size);
  const splash = markGrid(coverage(svg, SPLASH_ROWS), SPLASH_ROWS, size);
  const path = new URL('../../src/ui/header/mark.ts', import.meta.url).pathname;

  await writeFile(path, await formatModule(markModule(grid, splash)));

  for (const each of [grid, splash]) {
    console.log(`${each.length / 2} × ${each[0]?.length ?? 0}.`);
  }
}
