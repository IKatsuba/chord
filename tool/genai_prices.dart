/// Writes lib/session/price_data.dart from an installed copy of
/// @pydantic/genai-prices at the version the port pins, read with Node.
/// Install it anywhere (`npm install @pydantic/genai-prices@0.2.3` in a
/// scratch directory), then, from anywhere, with that copy's folder:
///
/// ```sh
/// dart run tool/genai_prices.dart --package node_modules/@pydantic/genai-prices
/// ```
///
/// The data keeps what the port's pricing reads (each provider's match and
/// fallbacks, each model's match, prices and context window) and leaves out
/// the rest (names, descriptions, comments, URLs, extractors, price
/// variants, which only a price context reaches).
library;

import 'dart:convert';
import 'dart:io';

import 'package:path/path.dart' as p;

/// The version the original pins; the generator refuses any other.
const pinned = '0.2.3';

/// What Node runs: the package's providers, as `waitForUpdate` gives them,
/// and its unit table, which the bundle keeps unexported as `ee`.
const _dump = r'''
import { readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
const dir = process.argv[2];
const mod = await import(pathToFileURL(`${dir}/dist/index.js`).href);
const providers = await mod.waitForUpdate();
const text = readFileSync(`${dir}/dist/index.js`, 'utf8');
const start = text.indexOf('], ee = {') + 8;
const end = text.indexOf('};\nclass te', start) + 1;
if (start < 8 || end < 1) throw new Error('unit table not found');
const units = (0, eval)('(' + text.slice(start, end) + ')');
process.stdout.write(JSON.stringify({ units, providers }));
''';

Future<void> main(List<String> args) async {
  final at = args.indexOf('--package');
  if (at < 0 || at + 1 >= args.length) {
    stderr.writeln(
      'Usage: dart run tool/genai_prices.dart --package <dir>, the folder of '
      'an installed @pydantic/genai-prices $pinned.',
    );
    exit(64);
  }
  final port = p.dirname(p.dirname(p.fromUri(Platform.script)));
  exit(
    await generatePrices(
      package: args[at + 1],
      out: p.join(port, 'lib', 'session', 'price_data.dart'),
    ),
  );
}

/// Writes [out] from the genai-prices installed at [package], read with
/// [node]; answers the exit code, saying on stderr why it is not 0.
Future<int> generatePrices({
  required String package,
  required String out,
  String node = 'node',
}) async {
  package = p.absolute(package);
  final manifest = File(p.join(package, 'package.json'));
  if (!manifest.existsSync()) {
    stderr.writeln('No genai-prices at $package.');
    return 1;
  }
  final version =
      (jsonDecode(manifest.readAsStringSync()) as Map)['version'] as String;
  if (version != pinned) {
    stderr.writeln('genai-prices is $version there; the port pins $pinned.');
    return 1;
  }

  final scratch = Directory.systemTemp.createTempSync('genai-prices-');
  try {
    final script = File(p.join(scratch.path, 'dump.mjs'))
      ..writeAsStringSync(_dump);
    final run = await Process.run(node, [script.path, package]);
    if (run.exitCode != 0) {
      stderr.write(run.stderr);
      return 1;
    }
    final dumped = jsonDecode(run.stdout as String) as Map<String, Object?>;
    final data = {
      'units': dumped['units'],
      'providers': [
        for (final provider in dumped['providers'] as List)
          _provider(provider as Map<String, Object?>),
      ],
    };
    final json = jsonEncode(data);
    if (json.contains("'''")) throw StateError('the data holds three quotes');
    final file = File(out);
    file.writeAsStringSync('''
// Generated by tool/genai_prices.dart from @pydantic/genai-prices $pinned;
// do not edit. https://github.com/pydantic/genai-prices
