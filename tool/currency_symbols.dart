/// Writes lib/ui/transcript/currency_symbols.dart, and the probe its test
/// compares with, from Node's Intl, en-US, as chord's formatCost writes a
/// cost. Run from anywhere:
///
///   dart run tool/currency_symbols.dart
///
/// The table pins the ICU and the CLDR it carries; the generator refuses a
/// Node with another ICU.
library;

import 'dart:convert';
import 'dart:io';

import 'package:path/path.dart' as p;

/// The ICU the table was made with, and the CLDR it carries.
const pinnedIcu = '78.1';
const pinnedCldr = '48';

/// What Node runs: each currency Intl knows, a cost at two and four digits.
const _probe = r'''
const codes = Intl.supportedValuesOf('currency');
const format = (currency, amount, digits) =>
  new Intl.NumberFormat('en-US', {
    style: 'currency',
    currency,
    minimumFractionDigits: digits,
    maximumFractionDigits: digits,
  }).format(amount);
process.stdout.write(JSON.stringify({
  icu: process.versions.icu,
  costs: Object.fromEntries(
    codes.map((code) => [code, [format(code, 3, 2), format(code, 0.03, 4)]]),
  ),
}));
''';

Future<void> main() async {
  exit(
    await generateSigns(port: p.dirname(p.dirname(p.fromUri(Platform.script)))),
  );
}

/// Writes the table and its probe under the repository [port], from
/// [node]'s Intl; answers the exit code, saying on stderr why it is not 0.
Future<int> generateSigns({required String port, String node = 'node'}) async {
  final scratch = Directory.systemTemp.createTempSync('currency-symbols-');
  try {
    final script = File(p.join(scratch.path, 'probe.mjs'))
      ..writeAsStringSync(_probe);
    final run = await Process.run(node, [script.path]);
    if (run.exitCode != 0) {
      stderr.write(run.stderr);
      return 1;
    }
    final probe = jsonDecode(run.stdout as String) as Map<String, Object?>;
    if (probe['icu'] != pinnedIcu) {
      stderr.writeln(
        'Node has ICU ${probe['icu']}; the table pins $pinnedIcu.',
      );
      return 1;
    }
    final costs = (probe['costs'] as Map).cast<String, List<Object?>>();
    final signs = <String, String>{};
    for (final MapEntry(:key, :value) in costs.entries) {
      final two = value.first as String;
      if (!two.endsWith('3.00')) {
        stderr.writeln('$key does not end in its amount: $two');
        return 1;
      }
      signs[key] = two.substring(0, two.length - '3.00'.length);
    }

    File(p.join(port, 'test', 'fixtures', 'currency', 'original_probe.json'))
      ..createSync(recursive: true)
      ..writeAsStringSync(
        '${const JsonEncoder.withIndent('  ').convert(probe)}\n',
      );

    final entries = [
      for (final MapEntry(:key, :value) in signs.entries)
