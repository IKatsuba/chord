/**
 * Freeze the ACP Registry's npx and uvx agents into src/registry.ts.
 *
 *   bun dev registry   fetch the registry and rewrite the module
 *
 * chord never reads the registry at run time, so an agent's version moves only
 * when this runs and the diff is committed.
 */
import { writeFile } from 'node:fs/promises';
import { valid } from '@renovatebot/pep440';
import { z } from '@zod/zod';
import npa from 'npm-package-arg';
import { parsePipRequirementsLine } from 'pip-requirements-js';
import { formatModule } from '../format.ts';

export const REGISTRY_URL =
  'https://cdn.agentclientprotocol.com/registry/v1/latest/registry.json';

const Package = z.object({
  package: z.string(),
  args: z.array(z.string()).optional(),
  env: z.record(z.string(), z.string()).optional(),
});

// Only what the module keeps is checked, so a field the registry adds later
// does not stop a refresh.
const Registry = z.object({
  agents: z.array(
    z.object({
      id: z.string(),
      name: z.string(),
      website: z.string().optional(),
      repository: z.string().optional(),
      distribution: z.object({
        npx: Package.optional(),
        uvx: Package.optional(),
      }),
    }),
  ),
});

/** One agent as the generated module writes it. */
export interface FrozenAgent {
  id: string;
  name: string;
  runner: 'npx' | 'uvx';
  package: string;
  version: string;
  args: string[];
  env: Record<string, string>;
  /** Where the agent says to install it, for a refusal to point at. */
  website?: string;
  repository?: string;
}

/**
 * The registry's agents that npx or uvx starts, in its order, npx where it
 * offers both. A package without an exact version is refused rather than
 * frozen, since a tag or a range would move under chord without a commit.
 */
export function frozenAgents(registry: unknown): FrozenAgent[] {
  return Registry.parse(registry).agents.flatMap((agent) => {
    const { npx, uvx } = agent.distribution;
    const runner =
      npx === undefined ? (uvx === undefined ? undefined : 'uvx') : 'npx';
    const found = npx ?? uvx;

    if (runner === undefined || found === undefined) {
      return [];
    }

    const exact =
      runner === 'npx' ? npmExact(found.package) : pythonExact(found.package);

    if (exact === undefined) {
      throw new Error(
        `${agent.id}: "${found.package}" is not a package at an exact version.`,
      );
    }

    return [
      {
        id: agent.id,
        name: agent.name,
        runner,
        ...exact,
        args: found.args ?? [],
        env: found.env ?? {},
        ...(agent.website === undefined ? {} : { website: agent.website }),
        ...(agent.repository === undefined
          ? {}
          : { repository: agent.repository }),
      },
    ];
  });
}

function npmExact(spec: string) {
  const parsed = npa(spec);

  return parsed.type !== 'version' || parsed.name === null
    ? undefined
    : { package: parsed.name, version: parsed.rawSpec };
}

/**
 * A uvx package is either uv's own `<name>@<version>`, which uv splits at the
 * `@` before anything else, or a PEP 508 requirement, which only pins with a
 * single `==` and no extras or markers.
 */
function pythonExact(spec: string) {
  const at = spec.indexOf('@');

  if (at !== -1) {
    const version = spec.slice(at + 1);

    return valid(version) === version
      ? { package: spec.slice(0, at), version }
      : undefined;
  }

  try {
    const parsed = parsePipRequirementsLine(spec);

    if (
      parsed?.type !== 'ProjectName' ||
      parsed.extras !== undefined ||
      parsed.environmentMarkerTree !== undefined
    ) {
      return undefined;
    }

    const [pin, ...more] = parsed.versionSpec ?? [];

    return pin === undefined ||
      more.length > 0 ||
      pin.operator !== '==' ||
      valid(pin.version) !== pin.version
      ? undefined
      : { package: parsed.name, version: pin.version };
  } catch {
    return undefined;
  }
}

/** The source of src/registry.ts, before the formatter lays it out. */
export function registryModule(
  agents: readonly FrozenAgent[],
  fetched: string,
): string {
  return `// Generated by \`bun dev registry\` from the ACP Registry,
// ${REGISTRY_URL},
// fetched ${fetched}. Do not edit: run the task again and commit the diff.

/**
 * An agent the ACP Registry offers through npx or uvx, at the version fetched,
 * with where it says to install it from.
 */
export interface RegistryAgent {
  readonly id: string;
  readonly name: string;
  readonly runner: 'npx' | 'uvx';
  readonly package: string;
  readonly version: string;
  readonly args: readonly string[];
  readonly env: Readonly<Record<string, string>>;
  readonly website?: string;
  readonly repository?: string;
}

export const FETCHED = ${JSON.stringify(fetched)};

export const REGISTRY_AGENTS: readonly RegistryAgent[] = [
${agents.map(entry).join('')}];
`;
}

function entry(agent: FrozenAgent): string {
  const fields = Object.entries(agent).map(
    ([key, value]) => `${key}: ${JSON.stringify(value)},`,
  );

  return `{ ${fields.join(' ')} },\n`;
}

/** Fetches the registry and rewrites src/registry.ts from it. */
export async function registry(): Promise<void> {
  const response = await fetch(REGISTRY_URL);

  if (!response.ok) {
    console.error(`${REGISTRY_URL}: ${response.status} ${response.statusText}`);
    process.exit(1);
  }

  const agents = frozenAgents(await response.json());
  const fetched = new Date().toISOString().slice(0, 10);
  const path = new URL('../../src/registry.ts', import.meta.url).pathname;

  await writeFile(path, await formatModule(registryModule(agents, fetched)));

  console.log(`${agents.length} agents from ${REGISTRY_URL}, ${fetched}.`);
}
